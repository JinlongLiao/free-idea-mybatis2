package io.github.jinlongliao.mybatis.workbench.database;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;

/**
 * 通过 PostgreSQL 系统目录重建所选独立表、分区父表或视图的结构定义。
 *
 * @author liaojinlong
 * @see <a href="https://www.postgresql.org/docs/current/functions-info.html">PostgreSQL 系统信息函数</a>
 * @see <a href="https://www.postgresql.org/docs/18/sql-alterview.html">PostgreSQL ALTER VIEW</a>
 * @since 2026/11/18 17:02
 */
final class PostgreSqlTableDdl {
	/**
	 * 从普通视图目录中读取已设置的权限和写入选项，按名称排序以供重放和比较。
	 *
	 * @see <a href="https://www.postgresql.org/docs/18/sql-createview.html">PostgreSQL CREATE VIEW</a>
	 */
	private static final String VIEW_OPTIONS = """
		(SELECT string_agg(option_name || ' = ' || pg_catalog.quote_literal(option_value), ', ' ORDER BY option_name)
		 FROM pg_catalog.pg_options_to_table(c.reloptions)
		 WHERE c.relkind = 'v' AND option_name IN ('security_barrier', 'security_invoker', 'check_option'))
		""";

	/**
	 * 一次查询获取列定义、约束和独立索引，避免分次查询读到不一致的目录版本。
	 */
	private static final String READ_DDL = """
		SELECT c.relkind,
		       c.relispartition,
		       CASE WHEN c.relispartition THEN pg_catalog.pg_get_expr(c.relpartbound, c.oid) END AS partition_bound,
		       (SELECT pg_catalog.quote_ident(parent_schema.nspname) || '.' || pg_catalog.quote_ident(parent.relname)
		        FROM pg_catalog.pg_inherits i
		        JOIN pg_catalog.pg_class parent ON parent.oid = i.inhparent
		        JOIN pg_catalog.pg_namespace parent_schema ON parent_schema.oid = parent.relnamespace
		        WHERE c.relispartition AND i.inhrelid = c.oid) AS partition_parent,
		       (SELECT string_agg('ALTER TABLE ' || pg_catalog.quote_ident(n.nspname) || '.'
		          || pg_catalog.quote_ident(c.relname) || ' ADD CONSTRAINT ' || pg_catalog.quote_ident(k.conname)
		          || ' ' || pg_catalog.pg_get_constraintdef(k.oid, true) || ';', chr(10)
		          ORDER BY CASE WHEN k.contype = 'f' THEN 1 ELSE 0 END, k.conname)
		        FROM pg_catalog.pg_constraint k
		        WHERE c.relispartition AND k.conrelid = c.oid AND k.contype IN ('p', 'u', 'c', 'f', 'x')
		          AND k.conislocal AND k.coninhcount = 0 AND k.conparentid = 0) AS partition_local_constraints,
		       CASE WHEN c.relkind = 'p' THEN pg_catalog.pg_get_partkeydef(c.oid) END AS partition_key_sql,
		       CASE WHEN c.relkind IN ('v', 'm') THEN pg_catalog.pg_get_viewdef(c.oid, true) END AS view_sql,
		       %s AS view_options,
		       (SELECT string_agg('ALTER VIEW ' || pg_catalog.quote_ident(n.nspname) || '.'
		          || pg_catalog.quote_ident(c.relname) || ' ALTER COLUMN ' || pg_catalog.quote_ident(a.attname)
		          || ' SET DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ';', chr(10) ORDER BY a.attnum)
		        FROM pg_catalog.pg_attrdef d
		        JOIN pg_catalog.pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
		        WHERE c.relkind = 'v' AND d.adrelid = c.oid AND NOT a.attisdropped) AS view_column_defaults,
		       (SELECT string_agg(
		          pg_catalog.quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
		          || CASE a.attidentity
		               WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
		               WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
		               ELSE CASE a.attgenerated
		                 WHEN 's' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') STORED'
		                 WHEN 'v' THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') VIRTUAL'
		                 ELSE CASE WHEN d.adbin IS NULL THEN ''
		                       ELSE ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) END
		                 END
		             END || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
		          E',\n  ' ORDER BY a.attnum)
		        FROM pg_catalog.pg_attribute a
		        LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
		        WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped) AS columns_sql,
		       (SELECT string_agg('CONSTRAINT ' || pg_catalog.quote_ident(k.conname) || ' '
		          || pg_catalog.pg_get_constraintdef(k.oid, true), E',\n  ' ORDER BY k.conname)
		        FROM pg_catalog.pg_constraint k
		        WHERE k.conrelid = c.oid AND k.contype IN ('p', 'u', 'c', 'f', 'x')) AS constraints_sql,
		       (SELECT string_agg(pg_catalog.pg_get_indexdef(i.indexrelid) || ';', E'\n' ORDER BY i.indexrelid)
		        FROM pg_catalog.pg_index i
		        WHERE i.indrelid = c.oid AND i.indisvalid
		          AND (NOT c.relispartition OR NOT EXISTS
		            (SELECT 1 FROM pg_catalog.pg_inherits index_parent WHERE index_parent.inhrelid = i.indexrelid))
		          AND NOT EXISTS
		          (SELECT 1 FROM pg_catalog.pg_constraint k
		           WHERE k.conindid = i.indexrelid AND k.conrelid = c.oid AND k.contype IN ('p', 'u', 'x'))) AS indexes_sql
		FROM pg_catalog.pg_class c
		JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = ? AND c.relname = ? AND c.relkind IN ('r', 'p', 'v', 'm')
		""".formatted(VIEW_OPTIONS);

	/**
	 * 目录读取由静态方法提供。
	 */
	private PostgreSqlTableDdl() {
	}

	/**
	 * 返回 PostgreSQL 独立表、分区父表、视图或物化视图的预览定义。
	 * 表列、约束和索引均由当前数据库目录生成。普通视图保留列默认值，分区表保留策略和键。子分区预览重建分区关系、边界、下级策略、独立索引及本地键、CHECK、外键和排他约束。列级覆盖等其他附属定义需另外处理。
	 *
	 * @param connection 当前 PostgreSQL JDBC 连接
	 * @param table      从当前连接读取的目标表定位
	 * @param qualified  引用过的模式和对象名
	 * @param messages 宿主提供的错误文案查询函数
	 * @return DDL 预览
	 * @throws SQLException 不支持所选对象、对象失效或目录查询失败
	 */
	static String readPostgreSqlDdl(Connection connection, JdbcTable table, String qualified,
		Function<String, String> messages) throws SQLException {
		try (var statement = connection.prepareStatement(READ_DDL)) {
			statement.setString(1, table.schema());
			statement.setString(2, table.name());
			statement.setQueryTimeout(15);
			try (var rows = statement.executeQuery()) {
				if (!rows.next()) {
					throw new SQLException(messages.apply("table.ddl.postgresql.unsupported"));
				}
				String indexes = rows.getString("indexes_sql");
				String partitionKey = rows.getString("partition_key_sql");
				String partitionClause = Objects.isNull(partitionKey) ? "" : " PARTITION BY " + partitionKey;
				if (rows.getBoolean("relispartition")) {
					String parent = rows.getString("partition_parent");
					String bound = rows.getString("partition_bound");
					if (Objects.isNull(parent) || Objects.isNull(bound)) {
						throw new SQLException(messages.apply("table.ddl.postgresql.unsupported"));
					}
					String ddl = "CREATE TABLE " + qualified + " PARTITION OF " + parent + " " + bound + partitionClause + ";";
					String localConstraints = rows.getString("partition_local_constraints");
					if (Objects.nonNull(localConstraints)) {
						ddl += "\n\n" + localConstraints;
					}
					return Objects.isNull(indexes) ? ddl : ddl + "\n\n" + indexes;
				}
				String kind = rows.getString("relkind");
				if ("v".equals(kind) || "m".equals(kind)) {
					String sql = rows.getString("view_sql").stripTrailing().replaceFirst(";\s*$", "");
					boolean materialized = "m".equals(kind);
					String options = formatViewOptions(rows.getString("view_options"));
					String ddl = "CREATE " + (materialized ? "MATERIALIZED " : "") + "VIEW " + qualified + options + " AS\n" + sql
						+ (materialized ? "\nWITH NO DATA;" : ";");
					String defaults = rows.getString("view_column_defaults");
					if (Objects.nonNull(defaults)) {
						ddl += "\n\n" + defaults;
					}
					return Objects.isNull(indexes) ? ddl : ddl + "\n\n" + indexes;
				}
				String columns = Objects.toString(rows.getString("columns_sql"), "");
				String constraints = rows.getString("constraints_sql");
				String definitions = Objects.isNull(constraints) ? columns : columns + ",\n  " + constraints;
				String ddl = "CREATE TABLE " + qualified + " (\n  " + definitions + "\n)" + partitionClause + ";";
				return Objects.isNull(indexes) ? ddl : ddl + "\n\n" + indexes;
			}
		}
	}

	/**
	 * 读取视图查询正文和权限、写入选项用于比较。对象名和独立索引由调用方另行处理。
	 *
	 * @param connection 当前 PostgreSQL 连接
	 * @param table 连接目录中的普通视图或物化视图
	 * @param messages 宿主提供的错误文案查询函数
	 * @return 视图选项与 PostgreSQL 根据目录反解析的查询正文
	 * @throws SQLException 对象不再存在或目录读取失败
	 */
	static String readPostgreSqlViewQuery(Connection connection, JdbcTable table,
		Function<String, String> messages) throws SQLException {
		try (var statement = connection.prepareStatement("""
			SELECT pg_catalog.pg_get_viewdef(c.oid, true), %s
			FROM pg_catalog.pg_class c
			JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
			WHERE n.nspname = ? AND c.relname = ? AND c.relkind IN ('v', 'm')
			""".formatted(VIEW_OPTIONS))) {
			statement.setString(1, table.schema());
			statement.setString(2, table.name());
			statement.setQueryTimeout(15);
			try (var rows = statement.executeQuery()) {
				if (rows.next()) {
					String options = formatViewOptions(rows.getString(2));
					return options.isEmpty() ? rows.getString(1) : options.stripLeading() + " AS\n" + rows.getString(1);
				}
				throw new SQLException(messages.apply("table.ddl.postgresql.unsupported"));
			}
		}
	}

	/**
	 * 把目录已引用的选项列表转成 CREATE VIEW 子句。
	 *
	 * @param options 已设置的选项，未设置时为空
	 * @return 带前置空格的 WITH 子句或空字符串
	 */
	private static String formatViewOptions(String options) {
		return Objects.isNull(options) ? "" : " WITH (" + options + ")";
	}

	/**
	 * 检查目标普通表是否没有分区或继承关系，以免局部约束草案影响其他表。
	 *
	 * @param connection 目标连接
	 * @param table 目标连接的表
	 * @return 普通表存在且没有父表或子表时为 true
	 * @throws SQLException 无法查询目标连接的目录
	 * @see <a href="https://www.postgresql.org/docs/18/sql-altertable.html">PostgreSQL ALTER TABLE</a>
	 */
	static boolean isStandalonePostgreSqlTable(Connection connection, JdbcTable table) throws SQLException {
		try (var statement = connection.prepareStatement("""
			SELECT 1
			FROM pg_catalog.pg_class c
			JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
			WHERE n.nspname = ? AND c.relname = ? AND c.relkind = 'r' AND NOT c.relispartition
			AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_inherits i WHERE i.inhrelid = c.oid)
			AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_inherits i WHERE i.inhparent = c.oid)
			""")) {
			statement.setString(1, table.schema());
			statement.setString(2, table.name());
			statement.setQueryTimeout(15);
			try (var rows = statement.executeQuery()) {
				return rows.next();
			}
		}
	}

	/**
	 * 读取 JDBC 元数据标识的分区表的策略和键，用于报告结构差异。
	 *
	 * @param connection 当前 PostgreSQL JDBC 连接
	 * @param table 来自 JDBC 元数据的对象定位
	 * @param messages 宿主提供的错误文案查询函数
	 * @return 分区策略和键，普通表返回空
	 * @throws SQLException 分区表在比较期间被删除或目录查询失败
	 */
	static String readPostgreSqlPartitionKey(Connection connection, JdbcTable table,
		Function<String, String> messages) throws SQLException {
		if (!"PARTITIONED TABLE".equals(table.type())) {
			return null;
		}
		try (var statement = connection.prepareStatement("""
			SELECT pg_catalog.pg_get_partkeydef(c.oid)
			FROM pg_catalog.pg_class c
			JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
			WHERE n.nspname = ? AND c.relname = ? AND c.relkind = 'p'
			""")) {
			statement.setString(1, table.schema());
			statement.setString(2, table.name());
			statement.setQueryTimeout(15);
			try (var rows = statement.executeQuery()) {
				if (rows.next()) {
					return rows.getString(1);
				}
				throw new SQLException(messages.apply("table.ddl.missing"));
			}
		}
	}

	/**
	 * 递归读取所选父表下的分区边界及子分区策略。与根表同模式的分区使用相对名称，便于跨模式比较。
	 *
	 * @param connection 当前 PostgreSQL JDBC 连接
	 * @param table 分区父表的 JDBC 定位
	 * @return 按路径排序的子分区定义
	 * @throws SQLException 目录查询失败
	 * @see <a href="https://www.postgresql.org/docs/current/catalog-pg-inherits.html">PostgreSQL 直接继承关系</a>
	 * @see <a href="https://www.postgresql.org/docs/current/catalog-pg-class.html">PostgreSQL 分区边界目录</a>
	 */
	static Map<String, List<String>> readPostgreSqlPartitionBounds(Connection connection, JdbcTable table) throws SQLException {
		try (var statement = connection.prepareStatement("""
			WITH RECURSIVE partition_tree(oid, root_schema, partition_path) AS (
			  SELECT root.oid, root.relnamespace, ''::text COLLATE "C"
			  FROM pg_catalog.pg_class root
			  JOIN pg_catalog.pg_namespace root_schema ON root_schema.oid = root.relnamespace
			  WHERE root_schema.nspname = ? AND root.relname = ? AND root.relkind = 'p'
			  UNION ALL
			  SELECT child.oid, tree.root_schema,
			         pg_catalog.concat_ws(' / ', NULLIF(tree.partition_path, ''),
			           CASE WHEN child.relnamespace = tree.root_schema THEN pg_catalog.quote_ident(child.relname)
			                ELSE pg_catalog.format('%I.%I', child_schema.nspname, child.relname) END)
			  FROM partition_tree tree
			  JOIN pg_catalog.pg_inherits inheritance ON inheritance.inhparent = tree.oid
			  JOIN pg_catalog.pg_class child ON child.oid = inheritance.inhrelid AND child.relispartition
			  JOIN pg_catalog.pg_namespace child_schema ON child_schema.oid = child.relnamespace
			)
			SELECT tree.partition_path,
			       pg_catalog.pg_get_expr(child.relpartbound, child.oid) AS partition_bound,
			       CASE WHEN child.relkind = 'p' THEN pg_catalog.pg_get_partkeydef(child.oid) END AS partition_key
			FROM partition_tree tree
			JOIN pg_catalog.pg_class child ON child.oid = tree.oid
			WHERE tree.partition_path <> ''
			ORDER BY tree.partition_path COLLATE "C"
			""")) {
			statement.setString(1, table.schema());
			statement.setString(2, table.name());
			statement.setQueryTimeout(15);
			try (var rows = statement.executeQuery()) {
				Map<String, List<String>> partitions = new LinkedHashMap<>();
				while (rows.next()) {
					String bound = rows.getString("partition_bound");
					String partitionKey = rows.getString("partition_key");
					partitions.put(rows.getString("partition_path"), Objects.isNull(partitionKey)
						? List.of(bound) : List.of(bound, "PARTITION BY " + partitionKey));
				}
				return partitions;
			}
		}
	}
}
